function parsePricingSeed(source) {
  const functionStart = source.indexOf("fn seed_model_pricing");
  const arrayStart = source.indexOf("let pricing_data = [", functionStart);
  const arrayEnd = source.indexOf("\n        ];", arrayStart);
  if (functionStart < 0 || arrayStart < 0 || arrayEnd < 0) {
    throw new Error("Unable to locate CC Switch model pricing seed");
  }
  const block = source.slice(arrayStart, arrayEnd);
  return [...block.matchAll(/\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,?\s*\)/g)]
    .map((match) => match.slice(1));
}

async function fetchWithRetry(url, attempts) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return await fetch(url, { headers: { "User-Agent": "Relay-Pool-Desktop" } });
    } catch (error) {
      lastError = error;
      if (attempt < attempts) {
        await new Promise((resolve) => setTimeout(resolve, attempt * 500));
      }
    }
  }
  throw lastError;
}

function renderRow(row) {
  return `    BuiltinModelBasePrice {
        id: "${escapeRust(row.id)}",
        provider: "${escapeRust(row.provider)}",
        model: "${escapeRust(row.model)}",
        display_name: "${escapeRust(row.displayName)}",
        input_price: ${rustOption(row.inputPrice)},
        output_price: ${rustOption(row.outputPrice)},
        cache_creation_price: ${rustOption(row.cacheCreationPrice)},
        cache_read_price: ${rustOption(row.cacheReadPrice)},
    },`;
}

function providerForModel(model) {
  const rules = [
    ["anthropic", /^(claude-)/],
    ["google", /^(gemini-)/],
    ["deepseek", /^(deepseek-)/],
    ["moonshotai", /^(kimi-|k3$)/],
    ["minimax", /^(minimax-)/],
    ["zhipuai", /^(glm-)/],
    ["xiaomi", /^(mimo-)/],
    ["alibaba", /^(qwen|qwq-)/],
    ["xai", /^(grok-)/],
    ["mistral", /^(mistral-|devstral-|magistral-|codestral-)/],
    ["cohere", /^(command-)/],
    ["stepfun", /^(step-)/],
    ["volcengine", /^(doubao-)/],
    ["tencent", /^(hunyuan-|hy3$)/],
    ["openai", /^(gpt-|o[134](?:-|$)|codex-)/],
  ];
  return rules.find(([, pattern]) => pattern.test(model))?.[0] ?? "custom";
}

function decimal(value) {
  const number = Number(value);
  if (!Number.isFinite(number) || number < 0) throw new Error(`Invalid pricing value: ${value}`);
  return number;
}

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function rustOption(value) {
  const literal = Number.isInteger(value) ? `${value}.0` : String(value);
  return `Some(${literal})`;
}

function escapeRust(value) {
  return String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"');
}
