async function fetchWithRetry(url, attempts) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return await fetch(url, { headers: { "User-Agent": "Relay-Pool-Desktop" } });
    } catch (error) {
      lastError = error;
      if (attempt < attempts) {
        await new Promise((resolve) => setTimeout(resolve, attempt * 500));
      }
    }
  }
  throw lastError;
}

function renderRow(row) {
  return `    BuiltinModelBasePrice {
        id: "${escapeRust(row.id)}",
        provider: "${escapeRust(row.provider)}",
        model: "${escapeRust(row.model)}",
        input_price: ${rustOption(row.inputPrice)},
        output_price: ${rustOption(row.outputPrice)},
        input_price_priority: ${rustOption(row.inputPricePriority)},
        output_price_priority: ${rustOption(row.outputPricePriority)},
        cache_creation_price: ${rustOption(row.cacheCreationPrice)},
        cache_creation_price_priority: ${rustOption(row.cacheCreationPricePriority)},
        cache_creation_price_above_1hr: ${rustOption(row.cacheCreationPriceAbove1Hr)},
        cache_read_price: ${rustOption(row.cacheReadPrice)},
        cache_read_price_priority: ${rustOption(row.cacheReadPricePriority)},
        long_context_input_token_threshold: ${rustIntegerOption(row.longContextInputTokenThreshold)},
        long_context_input_cost_multiplier: ${rustOption(row.longContextInputCostMultiplier)},
        long_context_output_cost_multiplier: ${rustOption(row.longContextOutputCostMultiplier)},
        supports_service_tier: ${row.supportsServiceTier},
        supports_prompt_caching: ${row.supportsPromptCaching},
        source_url: "${sourceUrl}",
        source_label: "Sub2API model pricing catalog",
        note: "Sub2API/LiteLLM ${escapeRust(row.mode)} pricing converted from USD per token to USD per M, including available cache and priority rates.",
    },`;
}

function normalizeProvider(provider) {
  if (provider === "gemini" || provider.startsWith("vertex_ai-")) return "google";
  return provider;
}

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function perMillion(value) {
  const number = finiteNumber(value);
  return number == null ? null : Number((number * 1_000_000).toPrecision(15));
}

function finiteNumber(value) {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function rustOption(value) {
  if (value == null) return "None";
  const number = Number(value);
  const literal = Number.isInteger(number) ? `${number}.0` : number.toString();
  return `Some(${literal})`;
}

function rustIntegerOption(value) {
  return value == null ? "None" : `Some(${Math.trunc(value)})`;
}

function escapeRust(value) {
  return String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"');
}
