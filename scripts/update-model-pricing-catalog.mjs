import { writeFile } from "node:fs/promises";

const sub2ApiCommit = "1e618dbc299fc0a82e9a690bcf2d5843be817113";
const checkedAt = "2026-08-12";
const sourcePath = "backend/resources/model-pricing/model_prices_and_context_window.json";
const sourceUrl = `https://github.com/Wei-Shaw/sub2api/blob/${sub2ApiCommit}/${sourcePath}`;
const rawUrl = `https://raw.githubusercontent.com/Wei-Shaw/sub2api/${sub2ApiCommit}/${sourcePath}`;
const supportedProviders = new Set([
  "openai",
  "text-completion-openai",
  "anthropic",
  "vertex_ai-language-models",
  "vertex_ai-embedding-models",
  "gemini",
  "deepseek",
  "volcengine",
  "bedrock",
]);

const response = await fetchWithRetry(rawUrl, 3);
if (!response.ok) {
  throw new Error(`Failed to fetch Sub2API pricing catalog: HTTP ${response.status}`);
}
const source = await response.json();
const rows = Object.entries(source)
  .filter(([, value]) => {
    if (!supportedProviders.has(value.litellm_provider)) return false;
    const hasTokenPrice = value.input_cost_per_token != null && value.output_cost_per_token != null;
    return hasTokenPrice || value.mode === "image_generation";
  })
  .map(([model, value]) => ({
    id: `builtin-${normalizeProvider(value.litellm_provider)}-${slug(model)}`,
    provider: normalizeProvider(value.litellm_provider),
    model,
    inputPrice: perMillion(value.input_cost_per_token),
    outputPrice: perMillion(value.output_cost_per_token),
    inputPricePriority: perMillion(value.input_cost_per_token_priority),
    outputPricePriority: perMillion(value.output_cost_per_token_priority),
    cacheCreationPrice: perMillion(value.cache_creation_input_token_cost),
    cacheCreationPricePriority: perMillion(value.cache_creation_input_token_cost_priority),
    cacheCreationPriceAbove1Hr: perMillion(value.cache_creation_input_token_cost_above_1hr),
    cacheReadPrice: perMillion(value.cache_read_input_token_cost),
    cacheReadPricePriority: perMillion(value.cache_read_input_token_cost_priority),
    longContextInputTokenThreshold: finiteNumber(value.long_context_input_token_threshold),
    longContextInputCostMultiplier: finiteNumber(value.long_context_input_cost_multiplier),
    longContextOutputCostMultiplier: finiteNumber(value.long_context_output_cost_multiplier),
    supportsServiceTier: value.supports_service_tier === true,
    supportsPromptCaching: value.supports_prompt_caching === true,
    mode: value.mode ?? "unknown",
  }))
  .sort((left, right) =>
    left.provider.localeCompare(right.provider) || left.model.localeCompare(right.model),
  );

if (rows.length !== 198) {
  throw new Error(`Expected 198 supported Sub2API prices, received ${rows.length}`);
}

